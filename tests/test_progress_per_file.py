def test_同一本书的两个文件各存各的读点(isolated):  # noqa: ARG001
    """EPUB 与 PDF 的读点互不覆盖 —— 这就是本期要的那个行为。"""
    db.set_progress("lib$a", 3, 30.0, cfi="cfi-epub", file_rel="x.epub")
    db.set_progress("lib$a", 900, 90.0, file_rel="y.pdf")

    # 直接查表（不走产品侧查询函数）：两行各是各的 locator 与 cfi ——
    # 「PDF 的 900 把 EPUB 的 3 冲掉」在这条断言下无处可藏
    assert {(r[1], r[2], r[4]) for r in _rows("lib$a")} == {
        ("x.epub", 3, "cfi-epub"), ("y.pdf", 900, ""),
    }

    # 精确取：给了 file_rel 就只认那个文件
    assert db.get_progress("lib$a", "x.epub")["locator"] == 3
    assert db.get_progress("lib$a", "y.pdf")["locator"] == 900
    assert db.get_progress("lib$a", "z.mobi") is None, "没读过的文件不该凭空有一行"


def test_书级进度取最近写入的那一行(isolated):  # noqa: ARG001
    """不给 ``file_rel`` 就是书级口径 = 用户最后在看的那个文件。"""
    db.set_progress("lib$b", 3, 30.0, file_rel="x.epub")
    db.set_progress("lib$b", 900, 90.0, file_rel="y.pdf")

    book = db.get_progress("lib$b")
    assert book["file_rel"] == "y.pdf" and book["locator"] == 900
    # 同一个口径必须贯穿到 all_progress（书架百分比走这条）
    assert db.all_progress()["lib$b"]["file_rel"] == "y.pdf"


def test_不带file_rel的写入是书级那一行且要清掉cfi(isolated):  # noqa: ARG001
    """KOReader / Komga / 标记已读完都走这条：与加这一列之前行为逐字节相同。"""
    db.set_progress("lib$c", 5, 50.0, cfi="cfi-精确坐标", file_rel="x.epub")
    db.set_progress("lib$c", 60, 60.0)          # 不带 file_rel、也不带 cfi

    row = db.get_progress("lib$c")
    assert row["file_rel"] == "" and row["locator"] == 60
    assert row["cfi"] == "", "非 NF 来源写入必须清掉精确坐标（否则恢复会跳回旧章）"
    # 文件那一行**没被动过** —— 书级写入不该毁掉文件的读点
    assert db.get_progress("lib$c", "x.epub")["locator"] == 5


def test_同一个文件重复写是更新而不是新增(isolated):  # noqa: ARG001
    """``ON CONFLICT(book_id, file_rel)`` 那个 DO UPDATE 的判据：行数不涨。"""
    db.set_progress("lib$d", 1, 10.0, file_rel="x.epub")
    db.set_progress("lib$d", 2, 20.0, file_rel="x.epub")

    assert len(_rows("lib$d")) == 1, "同一个文件写两次不该有两行"
    assert db.get_progress("lib$d", "x.epub")["locator"] == 2


def test_时间戳打平时两处口径给出同一个答案(isolated):  # noqa: ARG001
    """打平（同一毫秒写两行）时 ``get_progress`` 与 ``all_progress`` 必须一致。

    两处原先一个按 ``id DESC``、一个按 ``file_rel`` 比 —— 打平时各说各话：
    书架上的百分比与详情页「正在读哪个文件」会指向不同的文件。这里直接手写 SQL
    把 ``updated_at`` 定死来构造打平（不靠 ``time.time()`` 恰好撞上）。
    """
    c = _c()
    # 先写的 file_rel **大**、后写的 file_rel **小** —— 让「按 file_rel 比」与
    # 「按 id 比」在这份数据上给出**相反**的答案，判据才有区分力
    c.execute("INSERT INTO progress(book_id, file_rel, locator, percent, cfi, updated_at)"
              " VALUES('lib$tie','z.epub',1,10.0,'',777.0)")
    c.execute("INSERT INTO progress(book_id, file_rel, locator, percent, cfi, updated_at)"
              " VALUES('lib$tie','a.pdf',2,20.0,'',777.0)")
    c.commit()

    book = db.get_progress("lib$tie")
    every = db.all_progress()["lib$tie"]
    assert book["file_rel"] == every["file_rel"] == "a.pdf", (
        "打平时两处口径不一致：get_progress 给 %r，all_progress 给 %r"
        % (book["file_rel"], every["file_rel"])
    )
    assert book["locator"] == every["locator"] == 2
    # 反复调用必须稳定（原先的字典推导「最后一行赢」取决于物理顺序）
    assert {db.get_progress("lib$tie")["file_rel"] for _ in range(5)} == {"a.pdf"}


def test_all_progress不把内部排序键漏出去(isolated):  # noqa: ARG001
    """取最新那行要排序，但 ``id`` 是内部键：返回形状不该多出一个字段。"""
