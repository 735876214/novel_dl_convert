"""第 63 期 4/6：进度改成**按文件维度**（``progress`` 从「每书一行」到「每文件一行」）。

``progress`` 原来的唯一约束是 ``UNIQUE(book_id)``，一本书只有一个读点。多文件的书
（EPUB + PDF + 漫画）于是互相覆盖：在 PDF 里翻到 90%，EPUB 的读点就被冲掉了。
本期加一列 ``file_rel``，唯一约束改成 ``UNIQUE(book_id, file_rel)``：

- ``file_rel=''`` = 「这本书自己 / 不知道文件」—— KOReader 同步、Komga、标记已读完
  这些**不知道文件名**的写入方走这条，行为与加这一列之前逐字节相同（所有现存调用方
  一个字都不用改）；
- ``file_rel='x.epub'`` = 那个文件自己的读点，阅读器恢复位置时用。

**书级进度 = ``updated_at`` 最新的那一行**，不另存一份（另建表会变成双写，
漏一条的症状是「进度不更新」而不是报错）。所以 ``get_progress(book_id)`` /
``all_progress()`` 内部改成「取最新那行」之后，书级的下游全都不用动。

这个文件重点钉三件事，都是**改约束必须重建表**带出来的：

1. **重建不能丢数据**：老形状的表（带 ``id``、``UNIQUE(book_id)``）经 ``db.init()``
   之后行数必须不变、逐行内容必须保留。这是**计数断言**，也是防「静默归零」的
   唯一手段 —— 本仓有过一次血泪教训（``_remap_bookmarks``：唯一索引 + 整体 UPDATE
   → 撞约束 → 被 ``except`` 吞成「搬了 0 行」= 静默丢失）。进度比书签更糟：
   书签有墓碑可恢复，进度没了就是没了。
2. **重建可能死在中间**（两处后端的 DDL 都不在一笔事务里，见 ``_rebuild_progress``
   的 docstring），所以每种半成品都要自愈，且自愈的结果必须是「两张表的并集」。
3. **自愈判不出权威时一行不动**（而非猜一个）—— 宁可少搬，不可错搬。

整套用例在 SQLite 与 PG 两条后端下都要绿：DDL 与查询全部经 ``db._connect()``，
方言差异由 ``sqlcompat`` 翻译，本文件不出现任何只属于某一条后端的 SQL
（表在不在用 ``PRAGMA table_info`` 问 —— 它在 PG 上被映射到 ``information_schema``）。
"""
import pathlib

import pytest

from novelforge.core import db, epub_builder, library

#: 老形状（本期之前）的 ``progress``：**带 ``id``**、唯一约束是 ``UNIQUE(book_id)``。
#: ``id`` 不是可有可无的细节：真实老库一定有这么一列（``db.init()`` 的建表语句里
#: 就写着 ``id INTEGER PRIMARY KEY``），而它正好是「重建时绝对不要复制 id」那条
#: 结论的来由（PG 的 ``GENERATED BY DEFAULT`` 对显式插入不推序列，复制 id 会让
#: 重建之后第一次写入撞主键 —— 第 62 期补的坑）。夹具照**真实老库的形状**造，
#: 不照「够用就行」造：第 62 期就是因为夹具比真实老库少一列，让一个真 bug 一路绿过去。
_OLD_PROGRESS = (
    "CREATE TABLE {} (id INTEGER PRIMARY KEY, book_id TEXT NOT NULL,"
    " locator INTEGER NOT NULL, percent REAL NOT NULL DEFAULT 0,"
    " cfi TEXT NOT NULL DEFAULT '', updated_at REAL NOT NULL, UNIQUE(book_id))"
)

#: 新形状。测试里另写一份（而不是从被测代码里 import ``_PROGRESS_SQL``）是刻意的：
#: 形状变了就得**同时**改两边，而不是让被测代码自己证明自己。
_NEW_PROGRESS = (
    "CREATE TABLE {} (id INTEGER PRIMARY KEY, book_id TEXT NOT NULL,"
    " file_rel TEXT NOT NULL DEFAULT '', locator INTEGER NOT NULL,"
    " percent REAL NOT NULL DEFAULT 0, cfi TEXT NOT NULL DEFAULT '',"
    " updated_at REAL NOT NULL, UNIQUE(book_id, file_rel))"
)

#: 老库里的三行。locator / percent / cfi 各不相同：断言要能区分「第几行丢的」——
#: 三行长得一样的话，「搬丢了 2 行」与「搬串了行」在断言上看不出区别。
_OLD_ROWS = (("lib$k1", 11, 11.0, "cfi-1"), ("lib$k2", 12, 12.0, ""), ("lib$k3", 13, 13.0, "cfi-3"))


def _c():
    """库连接 —— 走 ``db._connect()``，于是 PG 后端下也吃 sqlcompat 的方言翻译。"""
    return db._connect()


def _exists(table: str) -> bool:
    """表在不在。``PRAGMA table_info`` 在两条后端下都是「有列就有表」，不需要分支。"""
    return bool(list(_c().execute("PRAGMA table_info({})".format(table))))


def _row_count(table: str) -> int:
    return int(_c().execute("SELECT COUNT(*) AS n FROM {}".format(table)).fetchone()["n"])


def _rows(book_id: "str | None" = None) -> list:
    """``progress`` 里 ``(book_id, file_rel, locator, percent, cfi)``，排序后返回。

    老形状的表**没有** ``file_rel`` 列，这时按 ``''`` 读 —— 于是「重建之前」与
    「重建之后」可以直接逐行对比：老行重建后就该是 ``file_rel=''``，
    照字面比出差异（而不是让 SQL 报「没有这一列」把用例本身弄挂）。
    """
    has_file_rel = "file_rel" in {r["name"] for r in _c().execute("PRAGMA table_info(progress)")}
    sql = "SELECT book_id, {} AS file_rel, locator, percent, cfi FROM progress".format(
        "file_rel" if has_file_rel else "''")
    params: tuple = ()
    if book_id is not None:
        sql += " WHERE book_id=?"
        params = (book_id,)
    return sorted(
        (str(r["book_id"]), str(r["file_rel"] or ""), int(r["locator"]),
         float(r["percent"]), str(r["cfi"] or ""))
        for r in _c().execute(sql, params)
    )


def _drop(*tables):
    c = _c()
    for t in tables:
        c.execute("DROP TABLE IF EXISTS {}".format(t))
    c.commit()


def _make_old(table: str = "progress", rows=_OLD_ROWS) -> None:
    """造一张老形状的表并填上 ``rows``。"""
    _drop(table)
    c = _c()
    c.execute(_OLD_PROGRESS.format(table))
    c.executemany(
        "INSERT INTO {}(book_id, locator, percent, cfi, updated_at) VALUES(?,?,?,?,?)".format(table),
        [(b, loc, pct, cfi, 1000.0 + loc) for b, loc, pct, cfi in rows],
    )
    c.commit()


def _make_new(table: str = "progress") -> None:
    _drop(table)
    _c().execute(_NEW_PROGRESS.format(table))


def _copy_into_progress(src: str = "progress_old", only: "str | None" = None) -> None:
    """照重建的做法把源表复制进新形状的 ``progress``。

    给了 ``only`` 就只搬一行 —— 那是「复制到一半」的样子。
    """
    where = " WHERE book_id='{}'".format(only) if only else ""
    _c().execute(
        "INSERT INTO progress(book_id, file_rel, locator, percent, cfi, updated_at)"
        " SELECT book_id, '', locator, percent, cfi, updated_at FROM {}{}".format(src, where)
    )


def _clean() -> None:
    """把表恢复成新形状的一张空表（自愈判不出权威那一例要收尾，见那个用例）。"""
    _drop("progress", "progress_old")
    db.init()


