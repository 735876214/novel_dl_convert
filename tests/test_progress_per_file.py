def test_老形状重建后行数不变且逐行内容保留(isolated):  # noqa: ARG001
    """**计数断言**。老表 3 行，重建后必须还是这 3 行，且每行的读点原样。

    这条是防「静默归零」的：重建写错最常见的样子不是报错，而是**搬了 0 行**
    却谁也不吭声（``_remap_bookmarks`` 那条教训的同形状坑）。

    ⚠️ **它只证明「一行没丢」，不证明「重建真的跑了」** —— 把 ``_rebuild_progress``
    整个改成空操作，这条照样绿：老形状的表按 ``''`` 读 ``file_rel``，看起来与
    重建之后逐行相同（实测如此）。「重建确实发生了」由下一条
    `test_重建之后唯一约束变成按文件` 负责，两条合起来才是完整判据。
    别把这条单独当成「迁移正确」的证据。
    """
    _make_old()
    before = _rows()
    assert len(before) == 3, "前置：老表得有 3 行，否则这条用例什么都没测"

    db.init()

    after = _rows()
    assert len(after) == len(before), "重建把行搬丢了：%d → %d" % (len(before), len(after))
    assert after == [("lib$k1", "", 11, 11.0, "cfi-1"),
                     ("lib$k2", "", 12, 12.0, ""),
                     ("lib$k3", "", 13, 13.0, "cfi-3")], after
    assert _exists("progress") and not _exists("progress_old"), "源表没清理干净"


def test_重建之后唯一约束变成按文件(isolated):  # noqa: ARG001
    """本期真正要的那条约束。**不加这条断言，重建写成「原样复制」也会绿。**"""
    _make_old()
    db.init()

    db.set_progress("lib$k1", 50, 50.0, file_rel="x.epub")   # 老行是 file_rel=''
    db.set_progress("lib$k1", 60, 60.0, file_rel="y.pdf")

    assert {r[1] for r in _rows("lib$k1")} == {"", "x.epub", "y.pdf"}
    assert len(_rows("lib$k1")) == 3, "约束还是按书的话，第二、三次写入会互相覆盖"


def test_重建是幂等的(isolated):  # noqa: ARG001
    """``init()`` 每次启动都跑 —— 跑第二遍不能把表又重建一次或丢行。"""
    _make_old()
    db.init()
    once = _rows()
    db.init()
    db.init()

    assert _rows() == once
    assert _exists("progress") and not _exists("progress_old")


