# ⑤ 接口层：file_rel 进出
# ---------------------------------------------------------------------------
# 前端送的就是 `library.detail()["files"][].name`（库内相对路径，Komga 布局下形如
# `系列名/书.epub`），与 `reading_sessions.file_rel` 是同一套取值约定。

def test_接口按文件维度读写(client, auth_headers):
    """PUT / GET 都认 ``file_rel``：给了就精确到那个文件，不给就是书级（最新那行）。"""
    h = auth_headers
    client.put("/api/books/lib$api/progress", headers=h,
               json={"locator": 3, "percent": 30.0, "file_rel": "x.epub"})
    client.put("/api/books/lib$api/progress", headers=h,
               json={"locator": 900, "percent": 90.0, "file_rel": "y.pdf"})

    a = client.get("/api/books/lib$api/progress?file_rel=x.epub", headers=h).json()
    assert a["locator"] == 3 and a["file_rel"] == "x.epub", a
    assert client.get("/api/books/lib$api/progress?file_rel=y.pdf",
                      headers=h).json()["locator"] == 900

    book = client.get("/api/books/lib$api/progress", headers=h).json()
    assert book["locator"] == 900 and book["file_rel"] == "y.pdf", \
        "书级要给出「最后在看的那个文件」，而且这个「哪个文件」本身也是答案的一部分"
    # 从来没读过那个文件 ⇒ 全零，且 `file_rel` 是 **null**（这一行不存在）。
    # 回 null 而不是空串：空串是「不知道文件的那次写入」自己的键，是个**存在的**行，
    # 调用方要能区分两者（见 `test_接口给空串要的是书级那一行而不是最新那行`）。
    assert client.get("/api/books/lib$api/progress?file_rel=从来没读过.epub",
                      headers=h).json() == {"locator": 0, "percent": 0, "cfi": "",
                                            "file_rel": None}


def test_接口给空串要的是书级那一行而不是最新那行(client, auth_headers):
    """``?file_rel=`` 与**不给** ``file_rel`` 落点不同，不能合并成一个。

    空串是「不知道文件的那次写入」（KOReader / Komga 写的那些）自己的键；
    不给是「读者最后在看的那个文件」。合并了的话，多设备下 KOReader 的进度
    就会把阅读器的位置顶掉。
    """
    h = auth_headers
    client.put("/api/books/lib$api2/progress", headers=h,
               json={"locator": 7, "percent": 7.0})                    # 书级 / 不知道文件
    client.put("/api/books/lib$api2/progress", headers=h,
               json={"locator": 8, "percent": 8.0, "file_rel": "z.epub"})

    empty = client.get("/api/books/lib$api2/progress?file_rel=", headers=h).json()
    latest = client.get("/api/books/lib$api2/progress", headers=h).json()
    assert empty["locator"] == 7 and empty["file_rel"] == "", empty
    assert latest["locator"] == 8 and latest["file_rel"] == "z.epub", latest

    # 「这一行**不存在**」必须是可判的，而且**不能**用 locator == 0 代替：
    # 第 0 章 / 第 1 页是合法位置，两者会混。`file_rel` 回 null 才是那个判据 ——
    # 空串是个合法取值（上面刚断言过），它区分不出「不存在」。
    # 前端恢复位置就靠它决定「要不要回落到书级」（`lib/readingProgress.ts`）。
    missing = client.get("/api/books/lib$api2/progress?file_rel=没读过.epub", headers=h).json()
    assert missing["file_rel"] is None, "这一行不存在时 file_rel 必须是 null：%r" % (missing,)
    assert missing["locator"] == 0, missing
    # 对照组：真的在**第 0 章**（合法位置）写过一行 ⇒ 它是存在的。两个响应都是
    # `locator == 0`，所以「locator 是不是 0」根本区分不出「没读过」与「读在第 0 章」——
    # 判据只能是 `file_rel` 是不是 null。
    client.put("/api/books/lib$api2/progress", headers=h,
               json={"locator": 0, "percent": 1.0, "file_rel": "开头.epub"})
    zero = client.get("/api/books/lib$api2/progress?file_rel=开头.epub", headers=h).json()
    assert zero["locator"] == 0 and zero["file_rel"] == "开头.epub", zero
    assert empty["file_rel"] is not None, "存在的那一行（哪怕 file_rel 是空串）不许回 null"


def test_奇怪的file_rel不会把进度保存弄失败(client, auth_headers):
    """``file_rel`` 是客户端传的字符串，但**绝不能**让它把一次普通的保存打成 400。

    ⚠️ 这条用的是**假 book_id**（``lib$api3`` 在库里不存在）⇒ ``library.by_id`` 返回
    ``None`` ⇒ ``api_set_progress`` 里生成 CFI 那一整段（含 ``_progress_file`` 与
    ``safe_path``）**压根不会执行**。所以：

    - 这里**不能**断言 ``cfi == ""`` —— 那是句**恒真的空转断言**，会让人以为
      「穿越值被拦下了」已经有人守着，而实际上没有任何东西在守。真正守着它的是
      下一条（真书 + 库根外的真 EPUB）；
    - 这条守的是另一件事：**书不存在**（进度可以写给一本扫不到的书 —— 同步先到、
      扫描后到就是这么发生的）时，一个奇怪的 file_rel 也不该把保存打成 500；
      以及进度本体照常落库。
    """
    h = auth_headers
    for bad in ("../逃出去.epub", "/etc/passwd", "a/b/c/太深.epub"):
        r = client.put("/api/books/lib$api3/progress", headers=h,
                       json={"locator": 4, "percent": 40.0, "offset": 5, "file_rel": bad})
        assert r.status_code == 200, "file_rel 把保存打成 %s 了：%s" % (r.status_code, r.text)
        body = client.get("/api/books/lib$api3/progress", headers=h,
                          params={"file_rel": bad}).json()
        assert body["locator"] == 4, "进度本体要照常落库：%r" % (body,)
        assert body["file_rel"] == bad, "回带的必须是原样那串：%r" % (body,)


