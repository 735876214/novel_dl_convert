# ③ 半成品自愈：重建死在中间的各种样子
# ---------------------------------------------------------------------------
# 两条后端的 DDL 都**不在一笔事务里**（SQLite 的 sqlite3 老事务模型：非 DML 语句前
# 先把挂起的那笔提交掉；pg._settle 第 2 条刻意照搬），所以「进程死在改名之后」是真实
# 可能的，而它的样子最难查：progress 不在，补列块看到空列集就整段跳过 —— 数据还在
# progress_old 里，但没有任何东西知道。下面每一例都**照现场的真实形状**造
#（哪种表是什么形状，由重建的语句顺序决定），并一律用**计数断言**收尾。

def test_自愈_只剩源表(isolated):  # noqa: ARG001
    """死在「已改名、还没建新表」：``progress`` 不在，``progress_old`` 是老形状。"""
    _make_old()
    _c().execute("ALTER TABLE progress RENAME TO progress_old")
    _c().commit()

    db.init()

    assert len(_rows()) == 3, "只剩源表时没把数据接回来"
    assert _exists("progress") and not _exists("progress_old")


def test_自愈_新表是空壳(isolated):  # noqa: ARG001
    """死在「建了新表、一行还没复制」：新表是新形状但空着，源表在老形状上躺着。"""
    _make_old()
    _c().execute("ALTER TABLE progress RENAME TO progress_old")
    _make_new()

    db.init()

    assert len(_rows()) == 3
    assert _exists("progress") and not _exists("progress_old")


def test_自愈_只复制了一部分(isolated):  # noqa: ARG001
    """死在复制途中 —— 最危险的一种：新表**看着像**建好了，其实只有一部分行。"""
    _make_old()
    _c().execute("ALTER TABLE progress RENAME TO progress_old")
    _make_new()
    _copy_into_progress(only="lib$k1")          # 3 行只搬了 1 行

    db.init()

    assert len(_rows()) == 3, "把「复制到一半」当成「已经搬完」，剩下的行被删没了"
    assert _exists("progress") and not _exists("progress_old")


def test_自愈_复制完了但源表没删(isolated):  # noqa: ARG001
    """死在「复制完、删源表之前」。这时新表已经是对的，只需清源表。"""
    _make_old()
    _c().execute("ALTER TABLE progress RENAME TO progress_old")
    _make_new()
    _copy_into_progress()

    db.init()

    assert len(_rows()) == 3
    assert _exists("progress") and not _exists("progress_old")


def test_自愈_复制窗口里别人写进新表的行不能陪葬(isolated):  # noqa: ARG001
    """半途自愈的判据是「**补齐**缺的行」，不是「把新表丢掉重来」。

    重来会把复制窗口里写进新表的行一起丢掉，而那些行是**别人的进度**，
    跟这次重建毫无关系。这里造出「新表 3 行（k1 + 两本别的书）、源表 3 行」
    —— 行数正好追平，所以：**比行数的判据会在这里判「已经搬完」，把源表里
    k2/k3 那两行删掉**；正确的结果是两张表的并集 5 行。
    """
    _make_old()
    _c().execute("ALTER TABLE progress RENAME TO progress_old")
    _make_new()
    _copy_into_progress(only="lib$k1")
    c = _c()
    c.executemany(
        "INSERT INTO progress(book_id, file_rel, locator, percent, cfi, updated_at)"
        " VALUES(?,?,?,?,?,?)",
        [("lib$other1", "", 1, 1.0, "", 500.0), ("lib$other2", "x.epub", 2, 2.0, "", 501.0)],
    )
    c.commit()
    assert (_row_count("progress"), _row_count("progress_old")) == (3, 3), "前置：行数要正好追平"

    db.init()

    got = {r[0] for r in _rows()}
    assert got == {"lib$k1", "lib$k2", "lib$k3", "lib$other1", "lib$other2"}, got
    assert _exists("progress") and not _exists("progress_old")


def test_自愈_新表里已有的行不被源表盖回(isolated):  # noqa: ARG001
    """补齐的方向只有一个：源表**缺的行**补进新表。新表里已有的那行是后写的，更权威。

    盖回去的话，用户在重建窗口里读到的新位置会被一个旧位置顶掉 —— 表现为
    「进度自己往回跳」，而且不报错。
    """
    _make_old()
    _c().execute("ALTER TABLE progress RENAME TO progress_old")
    _make_new()
    c = _c()
    c.execute("INSERT INTO progress(book_id, file_rel, locator, percent, cfi, updated_at)"
              " VALUES('lib$k1','',999,99.0,'cfi-新写的',9999.0)")
    c.commit()

    db.init()

    assert db.get_progress("lib$k1")["locator"] == 999, "新写的那行被源表的旧行盖回去了"
    assert db.get_progress("lib$k1")["cfi"] == "cfi-新写的"
    assert len(_rows()) == 3, "补齐时把同名的行插成了两行？"


def test_自愈_判不出权威时一行不动并抛错(isolated):  # noqa: ARG001
    """两张表并存、而当前表还是**旧形状** —— 重建造不出这个状态，判不出谁权威。

    此时**一行都不动**（宁可少搬不可错搬），但必须**抛**：安静返回的话服务照常起来，
    然后每次读写进度都 500（``no such column: file_rel``），日志里却没有任何一行
    说「迁移没跑」。抛出去则 ``db.init()`` 把服务挡在启动之前，消息点名两张表。
    """
    _make_new("progress_old")                    # 源表恰是新形状
    _c().execute("INSERT INTO progress_old(book_id, file_rel, locator, percent, cfi, updated_at)"
                 " VALUES('lib$stale','',9,9.0,'cfi-9',900.0)")
    _make_old("progress")                        # 当前表是旧形状
    _c().execute("INSERT INTO progress(book_id, locator, percent, cfi, updated_at)"
                 " VALUES('lib$cur',1,1.0,'cfi-1',100.0)")
    _c().commit()
    before = (_row_count("progress"), _row_count("progress_old"))

    with pytest.raises(RuntimeError) as ei:
        db.init()

