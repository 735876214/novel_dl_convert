"""书名解析（第 73 期）：``metadata.from_filename`` 与它那道**剥备注**判据 ``strip_count_note``。

需求来源（用户报）：连载的书在磁盘上常写成
``《转生魔女宣告毁灭（1-43话）》/第1卷/第1话.pdf`` ⇒ 书架上不该出现
「转生魔女宣告毁灭（1-43话）」这种尾巴，书名要自动修订为《转生魔女宣告毁灭》。
括号里那段是**集数说明**，不是书名的一部分 —— 它还会让同一本书与元数据提供商
抓回来的书名对不上（聚不到一起）。

判据为什么**窄**（宁可不剥）：剥错的代价是不对称的 ——
不剥只是书架上多一截尾巴；剥错会吃掉真的书名（``（0079）`` 变成 `0079`），
而且用户只能靠改磁盘上的文件名来救，而本项目承诺**源不可变**。

剥名发生在 ``from_filename`` 里（书名解析的唯一入口），所以对**所有**书生效 ——
包括存量书：`library.SCAN_RULE_VERSION` 会把旧索引认成过期、全量重探一次。
用户手工改过的书名在覆盖层里，读取时优先 ⇒ 这里剥不到它。
"""
from novelforge.core import metadata


# ---------------------------------------------------------------------------
# ① 端到端：文件名 → 书名（两个分支都要过这道判据）
# ---------------------------------------------------------------------------

#: ``(文件名, 期望书名)``。每条反例都对应一种**真实存在**的书名写法。
TITLE_CASES = [
    # 用户实况：注释在《》**里面**
    ("《转生魔女宣告毁灭（1-43话）》.cbz", "转生魔女宣告毁灭"),
    # 同义写法：全 N / 显式「第」/ 不带单位词 / 波浪号 / 连接号
    ("《转生魔女宣告毁灭（全43话）》.cbz", "转生魔女宣告毁灭"),
    ("《转生魔女宣告毁灭（第1-43话）》.cbz", "转生魔女宣告毁灭"),
    ("《转生魔女宣告毁灭（1-43）》.cbz", "转生魔女宣告毁灭"),
    ("《甲（1~43话）》.cbz", "甲"),
    ("《甲（1–43话）》.cbz", "甲"),
    ("《甲（1-43話）》.cbz", "甲"),
    ("《甲（1-43回）》.cbz", "甲"),
    # 半角括号 / 括号前有空格 / 括在《》外面，同样要剥
    ("《甲》(1-43话).cbz", "甲"),
    ("《甲》 （1-43话）.cbz", "甲"),
    ("《甲》（1-43话）作者：远瞳.txt", "甲"),
    # 第二个分支（**没有**《》的裸文件名）走同一道判据，否则两个分支会各说各话
    ("转生魔女宣告毁灭（1-43话）.cbz", "转生魔女宣告毁灭"),
    # 反例：无范围也无单位词 —— 那是标题里的一部分（年份 / 型号）
    ("《机动战士（0079）》.cbz", "机动战士（0079）"),
    # 反例：压根没有数字
    ("《甲（修订版）》.cbz", "甲（修订版）"),
    ("《甲（上册）》.cbz", "甲（上册）"),
    ("《甲（全本）》.cbz", "甲（全本）"),
    # 反例：**单卷**是这本书的身份，不是范围 —— 剥了会让各卷同名（其实是几本书）
    ("《甲（第7卷）》.cbz", "甲（第7卷）"),
    # 反例：只有「全N」没有单位词 ⇒ 与（0079）同一条理由：看不出是话数
    ("《甲（全43）》.cbz", "甲（全43）"),
    # 反例：备注不在**末尾**（括号后面还有书名的一部分）
    ("《甲（1-43话）乙》.cbz", "甲（1-43话）乙"),
    # 没有备注的普通书名一个字都不动
    ("《三体》.epub", "三体"),
    ("三体.txt", "三体"),
    ("三体（第二部）.epub", "三体（第二部）"),
]


def test_文件名到书名():
    """一张表定死：该剥的剥干净，不该剥的一个字不动。"""
    bad = []
    for name, want in TITLE_CASES:
        got = metadata.from_filename(name)["title"]
        if got != want:
            bad.append(f"from_filename({name!r})['title'] = {got!r}，期望 {want!r}")
    assert not bad, "书名解析不符：\n" + "\n".join(bad)


def test_作者不受剥备注影响():
    """剥的是书名，作者照旧解析（`《甲（1-43话）》作者：远瞳` ⇒ 甲 / 远瞳）。"""
    got = metadata.from_filename("《转生魔女宣告毁灭（1-43话）》作者：远瞳.txt")
    assert got == {"title": "转生魔女宣告毁灭", "author": "远瞳"}


def test_带不带书名号得到的书名一致():
    """`《甲（1-43话）》.cbz` 与 `甲（1-43话）.cbz` 必须同名 —— 两个分支共用一道判据。"""
    assert (metadata.from_filename("《甲（1-43话）》.cbz")["title"]
            == metadata.from_filename("甲（1-43话）.cbz")["title"] == "甲")


# ---------------------------------------------------------------------------
# ② 判据本体：`strip_count_note`
# ---------------------------------------------------------------------------

def test_剥备注():
    """正反例的**最小形态**（括号里那一段单独看）。"""
    assert metadata.strip_count_note("甲（1-43话）") == "甲"
    assert metadata.strip_count_note("甲（全43话）") == "甲"
    assert metadata.strip_count_note("甲（第1-43话）") == "甲"
    assert metadata.strip_count_note("甲（1-43）") == "甲"
    assert metadata.strip_count_note("甲（0079）") == "甲（0079）"
    assert metadata.strip_count_note("甲（修订版）") == "甲（修订版）"


def test_整段都是括号时不动():
    """书名整个就是 `（1-43话）` ⇒ 剥完就**空了** —— 那种情况宁可保留原样。"""
    assert metadata.strip_count_note("（1-43话）") == "（1-43话）"
    assert metadata.strip_count_note("  （全43话）  ") == "（全43话）"


def test_只剥一处且是幂等的():
    """多段备注只剥最靠后的一处，再剥一次结果不变（判据稳定，不会越剥越短）。"""
    once = metadata.strip_count_note("甲（全本）（1-43话）")
    assert once == "甲（全本）"
    assert metadata.strip_count_note(once) == once
    assert metadata.strip_count_note(metadata.strip_count_note("甲（1-43话）")) == "甲"


def test_空值不炸():
    """扫盘时文件名可能来自任何地方 —— 判据对空 / None 返回空串，不抛异常。"""
    assert metadata.strip_count_note("") == ""
    assert metadata.strip_count_note(None) == ""
    assert metadata.from_filename("")["title"] == ""
